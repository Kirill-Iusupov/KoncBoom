"""
Общие вспомогательные классы для админки.

ClickableRowAdminMixin — делает клик по ЛЮБОЙ точке строки в списке
(не только по тексту ссылки) переходом в объект. Обычный Django Admin
делает кликабельным только сам текст в колонках из list_display_links —
приходится целиться точно в цифру id. Этот миксин добавляет JS, который
слушает клик по всей строке <tr> и переходит по ссылке первой найденной
в ней <a> (то есть по той же ссылке, что уже дают list_display_links —
мы не создаём новых переходов, только расширяем кликабельную область).

Использование:
    class ProductAdmin(ClickableRowAdminMixin, ModelAdmin):
        ...

Работает как чистое усиление поверх list_display_links — если в строке
нет ссылки (например, всё попало в list_editable), JS просто ничего
не делает, поведение не ломается.
"""


class ClickableRowAdminMixin:
    class Media:
        js = ["admin/js/clickable_row.js"]